// Writes src/playbook.gen.ts from the playbook (playbook/*.md) and the View
// Type definitions (docs/view-types/*.md), so every runtime (Workers, Node,
// tests) gets them as plain strings with no file reads or loaders.
//
//   node scripts/build-playbook.mjs          # write it
//   node scripts/build-playbook.mjs --check  # exit 1 when it's stale
//
// src/playbook.test.ts runs the check too, so a stale file fails `pnpm test`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs"

const here = new URL("../", import.meta.url)
const root = new URL("../../", here)
const out = new URL("src/playbook.gen.ts", here)

export function generate() {
  const playbookDir = new URL("playbook/", here)
  const playbook = Object.fromEntries(
    readdirSync(playbookDir)
      .filter((f) => f.endsWith(".md"))
      .sort()
      .map((f) => [f.replace(/\.md$/, ""), readFileSync(new URL(f, playbookDir), "utf8")])
  )
  const typesDir = new URL("docs/view-types/", root)
  const viewTypes = Object.fromEntries(
    readdirSync(typesDir)
      .filter((f) => f.endsWith(".md") && !f.startsWith("_") && f !== "README.md")
      .sort()
      .map((f) => [f.replace(/\.md$/, ""), readFileSync(new URL(f, typesDir), "utf8")])
  )
  return [
    "// Generated by scripts/build-playbook.mjs from playbook/*.md and",
    "// docs/view-types/*.md. Don't edit: edit those and run the script.",
    "",
    "/** The playbook files, by name (`_contract`, `extract`, `build-view`, …). */",
    `export const PLAYBOOK_FILES: Record<string, string> = ${JSON.stringify(playbook, null, 2)}`,
    "",
    "/** Each View Type's definition (docs/view-types/<id>.md), by View Type id. */",
    `export const VIEW_TYPE_DOCS: Record<string, string> = ${JSON.stringify(viewTypes, null, 2)}`,
    "",
  ].join("\n")
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = generate()
  if (process.argv.includes("--check")) {
    const current = readFileSync(out, "utf8")
    if (current !== text) {
      console.error("src/playbook.gen.ts is stale: run node scripts/build-playbook.mjs")
      process.exit(1)
    }
    console.log("playbook ok")
  } else {
    writeFileSync(out, text)
    console.log("wrote src/playbook.gen.ts")
  }
}
